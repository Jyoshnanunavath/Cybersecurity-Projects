import { X } from 'lucide-react'

const STATUS_TEXT = {
  active: 'text-signal-active',
  inactive: 'text-signal-inactive',
  error: 'text-signal-error',
}

function Field({ label, value }) {
  return (
    <div>
      <p className="text-xs text-ink-muted">{label}</p>
      <p className="mt-1 font-mono text-sm text-ink-primary">{value}</p>
    </div>
  )
}

export default function HostDetails({ host, onClose }) {
  if (!host) return null

  return (
    <section className="mx-auto max-w-6xl px-6 pb-6">
      <div className="border border-line bg-base-900/60 p-6">
        <div className="flex items-start justify-between">
          <div>
            <p className="text-xs text-ink-muted">Host details</p>
            <p className="mt-1 font-mono text-lg font-semibold text-ink-primary">{host.ip}</p>
          </div>
          <button
            type="button"
            onClick={onClose}
            aria-label="Close host details"
            className="text-ink-muted transition-colors hover:text-ink-primary"
          >
            <X size={16} strokeWidth={2} />
          </button>
        </div>

        <div className="mt-5 grid grid-cols-2 gap-5 sm:grid-cols-4">
          <Field
            label="Status"
            value={<span className={`capitalize ${STATUS_TEXT[host.status]}`}>{host.status}</span>}
          />
          <Field label="Discovery result" value={host.result} />
          <Field label="Response time" value={host.latencyMs != null ? `${host.latencyMs} ms` : '—'} />
          <Field
            label="Scan timestamp"
            value={host.timestamp ? new Date(host.timestamp).toLocaleString() : '—'}
          />
        </div>

        <p className="mt-5 border-t border-line pt-4 text-xs text-ink-muted">
          This result was generated by the simulation engine from the IP address alone. No
          connection, packet, or request was made to this address.
        </p>
      </div>
    </section>
  )
}
